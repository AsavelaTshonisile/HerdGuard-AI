import React from 'react';
import { AlertTriangle, ShieldAlert } from 'lucide-react';

export default function DisclaimerBanner({ variant = 'info', message, className = '' }) {
  if (variant === 'urgent') {
    return (
      <div className={`p-4 rounded-xl border border-red-300 bg-red-50 text-red-900 shadow-sm ${className}`}>
        <div className="flex items-start space-x-3">
          <ShieldAlert className="w-6 h-6 text-red-600 flex-shrink-0 mt-0.5" />
          <div className="text-sm">
            <h4 className="font-bold text-red-800 uppercase tracking-wide text-xs">
              Urgent Animal Health Advisory
            </h4>
            <p className="mt-1 leading-relaxed">
              {message || (
                "Assessments generated by HerdGuard AI are preliminary and intended for early decision-support only. " +
                "They do NOT constitute a confirmed veterinary diagnosis. Contact your local State Veterinary Office or " +
                "registered Animal Health Technician immediately for clinical examination and official intervention."
              )}
            </p>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className={`p-3.5 rounded-xl border border-amber-200 bg-amber-50/70 text-amber-900 text-xs shadow-sm ${className}`}>
      <div className="flex items-start space-x-2.5">
        <AlertTriangle className="w-4 h-4 text-amber-600 flex-shrink-0 mt-0.5" />
        <div className="leading-relaxed">
          <span className="font-semibold text-amber-950">Official Regulatory Notice: </span>
          {message || (
            "HerdGuard AI complements South African livestock health monitoring and does not replace official DALRRD reporting channels, " +
            "veterinary practitioners, or statutory disease surveillance. AI outputs must never be treated as confirmed medical diagnoses."
          )}
        </div>
      </div>
    </div>
  );
}
